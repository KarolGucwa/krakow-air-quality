"""Kraków air quality dashboard (Streamlit).

Reads the Parquet exports of the dbt marts (``aq export-marts``), so it runs locally and
on Streamlit Community Cloud without dbt or the warehouse:

    streamlit run dashboard/app.py                       # data/marts
    MARTS_DIR=data/sample/marts streamlit run dashboard/app.py   # synthetic demo
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import duckdb
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
import streamlit as st

ROOT = Path(__file__).resolve().parents[1]
MARTS_DIR = Path(os.environ.get("MARTS_DIR", ROOT / "data" / "marts"))
if not MARTS_DIR.is_absolute():
    MARTS_DIR = ROOT / MARTS_DIR

# Palette: validated categorical order (fixed slot per station, never cycled),
# one-hue sequential blue ramp, chart ink. See README > Dashboard.
CATEGORICAL = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#6250d6", "#e34948"]
SEQUENTIAL = ["#cde2fb", "#9ec5f4", "#6da7ec", "#3987e5", "#256abf", "#184f95", "#0d366b"]
INK, INK_2, MUTED, GRID, AXIS = "#0b0b0b", "#52514e", "#898781", "#e1e0d9", "#c3c2b7"
BEFORE_AFTER = {"before ban": "#898781", "after ban": "#2a78d6"}
ORDER = {"ban_period": ["before ban", "after ban"]}
FONT = "system-ui, -apple-system, Segoe UI, sans-serif"

st.set_page_config(page_title="Kraków air quality", page_icon="🌫️", layout="wide")


def style(fig: go.Figure, height: int = 380, legend: bool = True) -> go.Figure:
    fig.update_layout(
        height=height, margin=dict(l=8, r=8, t=72, b=8), font=dict(family=FONT, color=INK_2, size=13),
        title=dict(y=0.98, yanchor="top", yref="container", x=0, xref="paper",
                   font=dict(color=INK, size=15)), plot_bgcolor="#fcfcfb", paper_bgcolor="#fcfcfb",
        hoverlabel=dict(bgcolor="white", font_color=INK, bordercolor=AXIS), showlegend=legend,
        legend=dict(orientation="h", yanchor="bottom", y=1.01, x=0, title_text="", font_color=INK_2),
    )
    fig.update_xaxes(gridcolor=GRID, linecolor=AXIS, tickfont_color=MUTED, title_font_color=INK_2,
                     zeroline=False)
    fig.update_yaxes(gridcolor=GRID, linecolor=AXIS, tickfont_color=MUTED, title_font_color=INK_2,
                     zeroline=False)
    return fig


@st.cache_data(show_spinner=False)
def load() -> dict[str, pd.DataFrame]:
    frames = {}
    for path in MARTS_DIR.glob("*.parquet"):
        # DuckDB instead of pyarrow: pyarrow's Parquet module is blocked on some Windows machines.
        frames[path.stem] = duckdb.sql(f"select * from read_parquet('{path.as_posix()}')").df()
    return frames


def meta() -> dict:
    path = MARTS_DIR / "_meta.json"
    return json.loads(path.read_text()) if path.exists() else {}


data = load()
info = meta()
required = {"marts__dim_station", "marts__fct_air_quality_daily", "dq__dq_station_monthly_report"}
if not required <= data.keys():
    st.title("Kraków air quality")
    st.warning(f"No mart exports found in `{MARTS_DIR}`. Run `make demo` (synthetic data) or "
               "`make pipeline` (real data), see README.")
    st.stop()

stations = data["marts__dim_station"].sort_values("station_code").reset_index(drop=True)
stations["label"] = stations["station_label"].fillna(stations["station_code"])
color_of = {row.label: CATEGORICAL[i % len(CATEGORICAL)] for i, row in stations.iterrows()}
label_of = dict(zip(stations["station_code"], stations["label"], strict=True))

daily = data["marts__fct_air_quality_daily"].copy()
daily["date_day"] = pd.to_datetime(daily["date_day"])
daily["station"] = daily["station_code"].map(label_of)
dim_date = data["marts__dim_date"].copy()
dim_date["date_day"] = pd.to_datetime(dim_date["date_day"])
daily = daily.merge(dim_date[["date_day", "year", "is_heating_season", "heating_season", "ban_period"]],
                    on="date_day", how="left")
pollutants = data["marts__dim_pollutant"].set_index("pollutant_code")
ban_date = pd.Timestamp("2019-09-01")

# ------------------------------------------------------------------ header & filters
st.title("Kraków air quality: PM2.5 and PM10")
st.caption("GIOŚ hourly measurements + Open-Meteo weather → dbt marts. "
           f"Data exported {info.get('exported_at', '?')}.")
if info.get("data_mode") == "synthetic":
    st.error("**DEMO – synthetic data.** These numbers are generated by `aq generate-sample` to "
             "demonstrate the pipeline. They are not measurements and support no conclusions about Kraków.",
             icon="⚠️")

f1, f2, f3 = st.columns([1, 3, 2])
pollutant = f1.radio("Pollutant", list(pollutants.index), horizontal=True)
chosen = f2.multiselect("Stations", list(stations["label"]), default=list(stations["label"]))
min_d, max_d = daily["date_day"].min().date(), daily["date_day"].max().date()
period = f3.slider("Period", min_value=min_d, max_value=max_d, value=(min_d, max_d), format="YYYY-MM")

who = float(pollutants.loc[pollutant, "who_24h_ugm3"])
eu = pollutants.loc[pollutant, "eu_24h_limit_ugm3"]
sel = daily[(daily["pollutant_code"] == pollutant) & daily["station"].isin(chosen)
            & daily["date_day"].between(pd.Timestamp(period[0]), pd.Timestamp(period[1]))]
complete = sel[sel["is_complete_day"]]
if complete.empty:
    st.info("No complete days for this selection.")
    st.stop()

# ------------------------------------------------------------------ headline numbers
ban = data.get("analysis__mart_coal_ban_weather_stratified", pd.DataFrame())
ban_sel = ban[(ban["pollutant_code"] == pollutant) & ban["station_code"].map(label_of).isin(chosen)] \
    if not ban.empty else ban
dq = data["dq__dq_station_monthly_report"].copy()
dq["month_start"] = pd.to_datetime(dq["month_start"])
dq["station"] = dq["station_code"].map(label_of)
dq_sel = dq[(dq["pollutant_code"] == pollutant) & dq["station"].isin(chosen)
            & dq["month_start"].between(pd.Timestamp(period[0]), pd.Timestamp(period[1]))]

k1, k2, k3, k4 = st.columns(4)
k1.metric("Mean of daily means", f"{complete['mean_ugm3'].mean():.1f} µg/m³",
          help="Complete days only (≥ 18 valid hours).")
share = complete["exceeds_who_24h"].mean() * 100
k2.metric(f"Station-days above WHO {who:.0f} µg/m³", f"{share:.0f} %",
          help="WHO 2021 24-hour guideline, evaluated on complete days.")
if not ban_sel.empty:
    k3.metric("Heating-season change after 2019 ban", f"{ban_sel['weather_adjusted_change_pct'].median():+.0f} %",
              help="Median over stations, weather-stratified comparison (same temperature, wind and "
                   "rain bands). See the 'Coal ban' tab.")
    k3.caption(f"same weather; naive before/after: {ban_sel['naive_change_pct'].median():+.0f} %")
if not dq_sel.empty:
    k4.metric("Hourly data completeness", f"{100 * dq_sel['valid_hours'].sum() / dq_sel['expected_hours'].sum():.1f} %",
              help="Valid hours / expected hours in the selection (Data quality tab).")

tabs = st.tabs(["Map", "Trends", "Coal ban", "Weather & week", "WHO exceedances", "Data quality"])

# ------------------------------------------------------------------ map
with tabs[0]:
    per_station = (complete.groupby("station").agg(mean=("mean_ugm3", "mean"),
                                                   who_days=("exceeds_who_24h", "sum"),
                                                   days=("exceeds_who_24h", "size")).reset_index())
    geo = stations.merge(per_station, left_on="label", right_on="station")
    geo = geo.dropna(subset=["latitude", "longitude"])
    c1, c2 = st.columns([3, 2])
    with c1:
        fig = px.scatter_map(geo, lat="latitude", lon="longitude", color="mean", size="mean",
                             size_max=26, zoom=10.6, hover_name="station_name",
                             hover_data={"district_name": True, "station_type": True, "mean": ":.1f",
                                         "who_days": True, "latitude": False, "longitude": False},
                             color_continuous_scale=SEQUENTIAL, map_style="carto-positron",
                             labels={"mean": "µg/m³", "who_days": "days > WHO",
                                     "district_name": "district", "station_type": "type"})
        fig.update_layout(coloraxis_colorbar=dict(title="µg/m³"))
        st.plotly_chart(style(fig, 470, legend=False), width="stretch")
    with c2:
        table = geo[["station", "district_name", "station_type", "mean", "who_days", "days"]].rename(columns={
            "station": "Station", "district_name": "District", "station_type": "Type",
            "mean": "Mean µg/m³", "who_days": "Days > WHO", "days": "Complete days"})
        st.dataframe(table.sort_values("Mean µg/m³", ascending=False).style.format({"Mean µg/m³": "{:.1f}"}),
                     hide_index=True, width="stretch")
        st.caption("Station types (GIOŚ): tło = background, komunikacyjna = traffic, "
                   "przemysłowa = industrial. Districts from seeds/station_districts.csv.")

# ------------------------------------------------------------------ trends
with tabs[1]:
    monthly = (complete.set_index("date_day").groupby("station")["mean_ugm3"]
               .resample("MS").mean().reset_index())
    fig = px.line(monthly, x="date_day", y="mean_ugm3", color="station", color_discrete_map=color_of,
                  labels={"mean_ugm3": f"{pollutant} monthly mean, µg/m³", "date_day": "", "station": ""},
                  title=f"{pollutant}: monthly mean of daily means")
    fig.update_traces(line_width=2, hovertemplate="%{x|%b %Y}: %{y:.1f} µg/m³")
    if period[0] <= ban_date.date() <= period[1]:
        fig.add_vline(x=ban_date, line_width=1, line_dash="dot", line_color=INK_2)
        fig.add_annotation(x=ban_date, y=1, yref="paper", text="coal ban 2019-09-01", showarrow=False,
                           xanchor="left", font_color=INK_2)
    fig.add_hline(y=who, line_width=1, line_dash="dash", line_color=MUTED)
    fig.add_annotation(x=0, xref="paper", y=who, text=f"WHO 24 h guideline {who:.0f}", showarrow=False,
                       xanchor="left", yanchor="bottom", font_color=MUTED, bgcolor="#fcfcfb")
    fig.update_layout(hovermode="x unified")
    st.plotly_chart(style(fig, 440), width="stretch")

    season_city = (complete.groupby([complete["date_day"].dt.year.rename("year"),
                                     complete["date_day"].dt.month.map(
                                         lambda m: "winter" if m in (12, 1, 2) else "spring" if m in (3, 4, 5)
                                         else "summer" if m in (6, 7, 8) else "autumn").rename("season")])
                   ["mean_ugm3"].mean().reset_index())
    fig = px.bar(season_city, x="year", y="mean_ugm3", color="season", barmode="group",
                 category_orders={"season": ["winter", "spring", "summer", "autumn"]},
                 color_discrete_sequence=CATEGORICAL[:4],
                 labels={"mean_ugm3": "µg/m³ (mean of selected stations)", "year": "", "season": ""},
                 title="Seasonal means by year")
    fig.update_traces(marker_line_color="#fcfcfb", marker_line_width=2,
                      hovertemplate="%{x} %{fullData.name}: %{y:.1f} µg/m³<extra></extra>")
    st.plotly_chart(style(fig, 360), width="stretch")

# ------------------------------------------------------------------ coal ban
with tabs[2]:
    hs = data.get("analysis__mart_heating_season_summary", pd.DataFrame())
    hs = hs[(hs["pollutant_code"] == pollutant) & hs["station_code"].map(label_of).isin(chosen)]
    if hs.empty:
        st.info("No heating-season summary for this selection.")
    else:
        city = (hs.groupby(["heating_season", "ban_period"])
                .agg(mean=("mean_ugm3", "mean"), temp=("temp_mean_c", "mean"),
                     hdd=("heating_degree_days", "mean"), days=("complete_days", "mean")).reset_index())
        city = city[city["days"] >= 120]  # complete seasons only
        c1, c2 = st.columns(2)
        fig = px.bar(city, x="heating_season", y="mean", color="ban_period",
                     color_discrete_map=BEFORE_AFTER, category_orders=ORDER,
                     labels={"mean": "µg/m³", "heating_season": "", "ban_period": ""},
                     title=f"Heating season (Oct–Mar) mean {pollutant}, average of stations")
        fig.update_traces(hovertemplate="%{x}: %{y:.1f} µg/m³<extra></extra>")
        c1.plotly_chart(style(fig, 360), width="stretch")
        fig = px.bar(city, x="heating_season", y="hdd", color="ban_period",
                     color_discrete_map=BEFORE_AFTER, category_orders=ORDER,
                     labels={"hdd": "heating degree days", "heating_season": "", "ban_period": ""},
                     title="How cold was the season? (heating degree days)")
        fig.update_traces(hovertemplate="%{x}: %{y:.0f} HDD<extra></extra>")
        c2.plotly_chart(style(fig, 360), width="stretch")

    if not ban_sel.empty:
        b = ban_sel.assign(station=ban_sel["station_code"].map(label_of)).sort_values("weather_adjusted_change_pct")
        fig = go.Figure()
        for _, r in b.iterrows():
            fig.add_trace(go.Scatter(x=[r["naive_change_pct"], r["weather_adjusted_change_pct"]],
                                     y=[r["station"]] * 2, mode="lines", line=dict(color=AXIS, width=2),
                                     showlegend=False, hoverinfo="skip"))
        fig.add_trace(go.Scatter(x=b["naive_change_pct"], y=b["station"], mode="markers", name="naive before/after",
                                 marker=dict(size=10, color=MUTED, line=dict(color="#fcfcfb", width=2)),
                                 hovertemplate="%{y}: %{x:.1f} % (naive)<extra></extra>"))
        fig.add_trace(go.Scatter(x=b["weather_adjusted_change_pct"], y=b["station"], mode="markers",
                                 name="same-weather comparison",
                                 marker=dict(size=10, color=CATEGORICAL[0], line=dict(color="#fcfcfb", width=2)),
                                 hovertemplate="%{y}: %{x:.1f} % (weather-stratified)<extra></extra>"))
        fig.add_vline(x=0, line_color=AXIS, line_width=1)
        fig.update_layout(title=f"Change in heating-season {pollutant} after the ban, % vs before",
                          xaxis_title="% change", yaxis_title="")
        st.plotly_chart(style(fig, 80 + 38 * len(b)), width="stretch")
        st.caption("Naive = all heating-season days after vs before 2019-09-01. Same-weather = means compared "
                   "within temperature × wind × rain bands, weighted by post-ban days (dbt model "
                   "mart_coal_ban_weather_stratified).")

    reg = data.get("analysis__coal_ban_regression", pd.DataFrame())
    if not reg.empty:
        r = reg[reg["pollutant"] == pollutant].copy()
        r["95 % CI"] = r.apply(lambda x: f"{x.ci_low_pct:+.1f} … {x.ci_high_pct:+.1f} %", axis=1)
        st.markdown("**Regression estimate (city mean, HAC errors)** – `analysis/coal_ban_effect.py`")
        st.dataframe(r[["specification", "days", "naive_pct", "effect_pct", "95 % CI", "p_value"]].rename(columns={
            "specification": "Model", "days": "Days", "naive_pct": "Naive %", "effect_pct": "Weather-adjusted %",
            "p_value": "p"}).style.format({"Naive %": "{:+.1f}", "Weather-adjusted %": "{:+.1f}", "p": "{:.3f}"}),
            hide_index=True, width="stretch")
        st.caption("'with trend' isolates the step at the ban from the gradual decline that started "
                   "earlier (stove replacement programme).")

# ------------------------------------------------------------------ weather & week
with tabs[3]:
    wr = data.get("analysis__mart_weather_response", pd.DataFrame())
    wr = wr[(wr["pollutant_code"] == pollutant) & wr["station_code"].map(label_of).isin(chosen)]
    c1, c2 = st.columns(2)
    for col, driver, title, xlab in [(c1, "temperature", "Daily mean vs temperature", "daily mean temperature, °C"),
                                     (c2, "wind", "Daily mean vs wind speed", "daily mean wind, m/s")]:
        part = wr[wr["driver"] == driver]
        part = (part.assign(w=part["mean_ugm3"] * part["days"]).groupby(["ban_period", "band_value"])
                .agg(w=("w", "sum"), days=("days", "sum")).reset_index())
        part = part[part["days"] >= 20].assign(mean=lambda d: d["w"] / d["days"])
        fig = px.line(part, x="band_value", y="mean", color="ban_period",
                     color_discrete_map=BEFORE_AFTER, category_orders=ORDER,
                      markers=True, labels={"band_value": xlab, "mean": "µg/m³", "ban_period": ""}, title=title)
        fig.update_traces(line_width=2, marker_size=8,
                          hovertemplate="%{x}: %{y:.1f} µg/m³<extra>%{fullData.name}</extra>")
        col.plotly_chart(style(fig, 340), width="stretch")

    wp = data.get("analysis__mart_weekly_profile", pd.DataFrame())
    wp = wp[(wp["pollutant_code"] == pollutant) & wp["station_code"].map(label_of).isin(chosen)]
    if not wp.empty:
        group = st.radio("Season", ["heating season", "non-heating season"], horizontal=True)
        g = wp[wp["season_group"] == group]
        g = (g.assign(w=g["mean_ugm3"] * g["hours"]).groupby(["iso_day_of_week", "day_name", "hour_local"])
             .agg(w=("w", "sum"), hours=("hours", "sum")).reset_index())
        g["mean"] = g["w"] / g["hours"]
        grid = g.pivot_table(index="day_name", columns="hour_local", values="mean")
        order = g.drop_duplicates("day_name").sort_values("iso_day_of_week")["day_name"]
        grid = grid.loc[list(order)]
        fig = px.imshow(grid, color_continuous_scale=SEQUENTIAL, aspect="auto",
                        labels=dict(x="local hour", y="", color="µg/m³"),
                        title=f"Average {pollutant} by weekday and hour ({group})")
        fig.update_traces(xgap=2, ygap=2, hovertemplate="%{y} %{x}:00 – %{z:.1f} µg/m³<extra></extra>")
        st.plotly_chart(style(fig, 330, legend=False), width="stretch")

# ------------------------------------------------------------------ WHO
with tabs[4]:
    yearly = (complete.groupby(["station", "year"])
              .agg(who=("exceeds_who_24h", "sum"), eu=("exceeds_eu_24h", "sum"), days=("date_day", "size"))
              .reset_index())
    grid = yearly.pivot_table(index="station", columns="year", values="who")
    fig = px.imshow(grid, color_continuous_scale=SEQUENTIAL, aspect="auto", text_auto=".0f",
                    labels=dict(x="", y="", color="days"),
                    title=f"Days with daily mean {pollutant} above the WHO 24-hour guideline ({who:.0f} µg/m³)")
    fig.update_traces(xgap=2, ygap=2, hovertemplate="%{y}, %{x}: %{z:.0f} days<extra></extra>")
    fig.update_xaxes(dtick=1)
    st.plotly_chart(style(fig, 90 + 42 * grid.shape[0], legend=False), width="stretch")
    if pd.notna(eu):
        st.caption(f"EU limit for {pollutant}: daily mean {eu:.0f} µg/m³ may be exceeded on at most "
                   f"{pollutants.loc[pollutant, 'eu_24h_allowed_exceedances']:.0f} days per year.")
        eu_grid = yearly.pivot_table(index="station", columns="year", values="eu")
        st.dataframe(eu_grid.astype("Int64"), width="stretch")
    st.caption("Only complete days (≥ 18 valid hours) are evaluated. The WHO 24-hour values are defined as "
               "the 99th percentile, i.e. about 3–4 exceedance days per year are compatible with the guideline.")

# ------------------------------------------------------------------ data quality
with tabs[5]:
    if dq_sel.empty:
        st.info("No data-quality rows for this selection.")
    else:
        grid = dq_sel.pivot_table(index="station", columns="month_start", values="completeness_pct")
        fig = px.imshow(grid, color_continuous_scale=SEQUENTIAL, aspect="auto", zmin=50, zmax=100,
                        labels=dict(x="", y="", color="% valid"),
                        title="Hourly completeness per station and month (valid / expected hours)")
        fig.update_traces(xgap=1, ygap=2, hovertemplate="%{y}, %{x|%b %Y}: %{z:.1f} %<extra></extra>")
        st.plotly_chart(style(fig, 90 + 40 * grid.shape[0], legend=False), width="stretch")

        summary = (dq_sel.groupby("station")[["expected_hours", "valid_hours", "missing_hours", "null_value_hours",
                                               "rejected_negative", "rejected_out_of_range", "rejected_spike",
                                               "duplicates"]].sum().reset_index())
        summary["completeness %"] = (100 * summary["valid_hours"] / summary["expected_hours"]).round(1)
        st.dataframe(summary.rename(columns={
            "station": "Station", "expected_hours": "Expected h", "valid_hours": "Valid h",
            "missing_hours": "Missing h", "null_value_hours": "of which null in API",
            "rejected_negative": "Rejected: negative", "rejected_out_of_range": "Rejected: > ceiling",
            "rejected_spike": "Rejected: isolated spike", "duplicates": "Duplicate versions"}),
            hide_index=True, width="stretch")
        st.caption("Model: dq.dq_station_monthly_report. Every rejected record with its reason is in "
                   "dq.dq_rejected_measurements; dbt test results are in schema test_failures.")
